CREATE TABLE clinics (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    name varchar(150) NOT NULL UNIQUE,
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_deleted boolean NOT NULL DEFAULT false,
    created_by uuid REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE visit_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    color_hex char(7) NOT NULL DEFAULT '#F26B6B',
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE clinic_visit_types (
    clinic_id integer NOT NULL REFERENCES clinics(id) ON DELETE CASCADE,
    visit_type_id integer NOT NULL REFERENCES visit_types(id) ON DELETE RESTRICT,
    PRIMARY KEY (clinic_id, visit_type_id)
);

CREATE TABLE facility_clinics (
    facility_id integer NOT NULL REFERENCES facilities(id) ON DELETE CASCADE,
    clinic_id integer NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
    is_enabled boolean NOT NULL DEFAULT true,
    is_unavailable boolean NOT NULL DEFAULT false,
    unavailable_reason varchar(255),
    unavailable_from timestamptz,
    unavailable_until timestamptz,
    updated_by uuid REFERENCES users(id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (facility_id, clinic_id),
    CHECK (NOT is_unavailable OR unavailable_reason IS NOT NULL)
);

CREATE TABLE doctor_clinics (
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    facility_id integer NOT NULL REFERENCES facilities(id) ON DELETE CASCADE,
    clinic_id integer NOT NULL REFERENCES clinics(id) ON DELETE RESTRICT,
    on_leave_from date,
    on_leave_to date,
    is_active boolean NOT NULL DEFAULT true,
    PRIMARY KEY (user_id, facility_id, clinic_id),
    CHECK (on_leave_from IS NULL OR on_leave_to IS NULL OR on_leave_to >= on_leave_from)
);

CREATE INDEX doctor_clinics_facility_clinic_idx
    ON doctor_clinics (facility_id, clinic_id, is_active);

