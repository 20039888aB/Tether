ALTER TABLE patients
    ADD COLUMN version integer NOT NULL DEFAULT 1,
    ADD CONSTRAINT patients_version_check CHECK (version >= 1);

ALTER TABLE consultation_notes
    ADD COLUMN version integer NOT NULL DEFAULT 1,
    ADD CONSTRAINT consultation_notes_version_check CHECK (version >= 1);

CREATE TABLE system_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_log_id bigint NOT NULL UNIQUE REFERENCES audit_logs(id) ON DELETE RESTRICT,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    actor_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
    category varchar(32) NOT NULL,
    action varchar(160) NOT NULL,
    resource_type varchar(160) NOT NULL,
    resource_id varchar(256),
    CHECK (
        category IN (
            'patient_access', 'nursing', 'clinical', 'admissions', 'laboratory',
            'pharmacy', 'billing', 'messaging', 'identity'
        )
    )
);

CREATE INDEX system_events_category_id_idx ON system_events (category, id);

CREATE FUNCTION reject_system_event_mutation() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'system_events is append-only';
END;
$$;

CREATE TRIGGER system_events_no_update
    BEFORE UPDATE OR DELETE ON system_events
    FOR EACH ROW EXECUTE FUNCTION reject_system_event_mutation();
